-- ============================================================
-- 功能说明：资源聚合支持手动排序（友链、收藏夹、趣味、旅拍、联系方式、快捷入口）
-- 变更内容：
--   1. resource_path.priority：排序优先级，数字小的在前面
-- 设计说明：
--   - 存量记录 priority 为 NULL，排序时统一排在已填写的记录之后，
--     同值再按各类型原有口径（友链/联系方式/快捷入口按 create_time，收藏夹按 title）兜底，
--     因此升级后前台展示顺序与升级前完全一致，无需回填
--   - 站长在后台「资源聚合」填写优先级即可调整顺序，留空表示不参与手动排序
--   - 本站信息、侧边栏背景为单记录类型，排序无实际意义，不受影响
--   - 全部语句可重复执行（IF NOT EXISTS 幂等），中断后可安全重跑
-- 日期：2026-11-17
-- ============================================================

ALTER TABLE `resource_path`
    ADD COLUMN IF NOT EXISTS `priority` int DEFAULT NULL COMMENT '排序优先级：数字小的在前面，未填写的按原有顺序排在后面' AFTER `remark`;